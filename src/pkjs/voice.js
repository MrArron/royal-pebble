// Offline voice commands (docs/DESIGN_V1_1.md §9.6, brief item 29).
//
// The watch records, the Pebble app turns speech into text on the phone (no
// internet at sea), and this module turns that text into one command:
//   parse(text, opts) -> {intent, A, B, cabin, A_target, B_target, A_how, B_how,
//                         reason?, topic?, deck?, via?, A_spot?, atA?}
//   A_spot: 'group' | 'multi_spot' | 'ashore' when A isn't one spot (no start);
//   atA: A came from "I'm at" (it also sets the spoken start, D4).
//   opts.ship     ship code (default 'HM'), picks the lexicon
//   opts.isCabin  function(number string) -> true when it's a cabin on the
//                 plans; index.js passes cabins.find, tests pass a made-up list
//
// Two parts, one owner each:
// - GRAMMAR (below, hand-edited): command words, restroom / elevator / stairs /
//   cabin words, numbers. Nothing ship-specific.
// - The venue lexicon (src/pkjs/data/voice-<SHIP>.js, generated by
//   tools/voice/build_voice.js from tools/voice/venue-mishearings-<SHIP>.json):
//   every venue name, alias and likely mishearing. Never add venue words here.
//
// Intents: SET_LOCATION, ROUTE (via 'snack' for a bite: Cafe Promenade), ROUTE_COMBINED,
// CLOSEST_RESTROOM, CLOSEST_BAR, CLOSEST_COFFEE,
// LOCATION_REFUSED (reason restroom | bar | coffee | elevator | stairs | deck | multi_spot |
// ashore | group), OUT_OF_SCOPE_KNOWN (topic schedule | hours | stateroom), INCOMPLETE,
// NO_MATCH (reason no_command | no_place | not_mapped | empty).
// A and B are spans or tokens: @mycabin, @cabin:N, @restroom, @elevator,
// @forelev, @aftelev, @stairs, @deck:N. A null A means the current start (9.4).
// A target with '|' is a group ("Arcade|Video Arcade"): as B, route to the
// nearest member; as a spoken location it is refused (reason group).
// Every result goes to the Heard/Matched confirm screen before anything happens.
// ES5, no dependencies besides the lexicon.
