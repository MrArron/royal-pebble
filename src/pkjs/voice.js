var BANK_TARGETS = {'@forelev': 'Fore elevators', '@aftelev': 'Aft elevators'};  // directory places

function cabinOf(v) {
  var m = /^@cabin:(\d+)$/.exec(v || '');
  return m ? m[1] : null;
}

function special(v) {
  return /^@/.test(v || '');
}

// Matches a clause's spans against the lexicon.
function resolve(p, match) {
  if (!p) {
    return p;
  }
  function target(v, deck) {
    if (!v) {
      return null;
    }
    if (BANK_TARGETS[v]) {
      return {t: BANK_TARGETS[v], flags: '', how: 'exact'};
    }
    return special(v) ? null : match(v, deck);
  }
  var out = {intent: p.intent, A: p.A || null, B: p.B || null, reason: p.reason, topic: p.topic, deck: p.deck};
  out.cabin = cabinOf(out.A) || cabinOf(out.B);
  if ((p.intent === 'SET_LOCATION' || p.intent === 'ROUTE_COMBINED') && refusedReason(out.A)) {
    return refused(out.A);
  }
  if ((p.intent === 'ROUTE' || p.intent === 'ROUTE_COMBINED') && out.B === '@restroom') {
    out.intent = 'CLOSEST_RESTROOM';
    out.B = null;
  }
  if (p.intent === 'ROUTE' && out.A && out.B && !special(out.A) && !target(out.A) &&
      categoryRequest(out.A + ' to ' + out.B)) {
    // Split at "to": "closest place to get a drink", "something to eat".
    out.B = out.A + ' to ' + out.B;
    out.A = null;
    p = copy(p);
    p.bare = true;
  }
  var cat = (p.intent === 'ROUTE' || p.intent === 'ROUTE_COMBINED') ?
    categoryOf(out.B) || (p.bare ? categoryRequest(out.B) : null) : null;
  if (cat && cat.intent === 'SNACK') {
    // A bite outside dining hours: Cafe Promenade, open 24 hours.
    out.via = 'snack';
    out.B = SNACK_PLACE.toLowerCase();
  } else if (cat) {
    // The nearest bar or coffee place, found by the route planner like the nearest restroom.
    out.intent = cat.intent;
    out.B = null;
  }
  var a = target(out.A, p.deckA || (p.intent !== 'ROUTE' ? p.deck : null));
  if (p.intent === 'SET_LOCATION' && out.A && !special(out.A) && !a) {
    // "I'm at the bar next to the Solarium": the named side.
    var two = out.A.match(/^(.+?) (?:near|by|next to|beside|outside|at|in front of) (.+)$/);
    if (two) {
      var right = target(cleanSpan(two[2])), left = target(cleanSpan(two[1]));
      if (right) {
        out.A = cleanSpan(two[2]);
        a = right;
      } else if (left) {
        out.A = cleanSpan(two[1]);
        a = left;
      }
    }
  }
  var b = target(out.B, p.deck);
  var unresolved = function(v, t) { return v && !special(v) && !t; };
  if (out.intent === 'ROUTE' && !out.A && unresolved(out.B, b)) {
    // "to" dropped: "Boardwalk the Solarium".
    var w = out.B.split(' ');
    for (var k = 1; k < w.length; k++) {
      var ta = target(cleanSpan(w.slice(0, k).join(' '))), tb = target(cleanSpan(w.slice(k).join(' ')));
      if (ta && tb && ta.how !== 'fuzzy' && tb.how !== 'fuzzy') {
        out.A = cleanSpan(w.slice(0, k).join(' '));
        out.B = cleanSpan(w.slice(k).join(' '));
        a = ta;
        b = tb;
        break;
      }
    }
  }
  if (unresolved(out.A, a) || unresolved(out.B, b)) {
    if (!p.bare && RX.event.test((out.A || '') + ' ' + (out.B || ''))) {
      return {intent: 'OUT_OF_SCOPE_KNOWN', topic: 'schedule', A: out.A, B: out.B, cabin: out.cabin};
    }
    return {intent: 'NO_MATCH', reason: p.bare ? 'no_command' : 'no_place', A: out.A, B: out.B, cabin: out.cabin};
  }
  // A bare phrase ("Play some music") only counts when it matched outright.
  if (p.bare && b && b.how !== 'exact') {
    return {intent: 'NO_MATCH', reason: 'no_command', A: out.A, B: out.B, cabin: out.cabin};
  }
  if ((a && a.flags.indexOf('N') !== -1) || (b && b.flags.indexOf('N') !== -1)) {
    return {intent: 'NO_MATCH', reason: 'not_mapped', A: out.A, B: out.B, cabin: out.cabin,
            A_target: a ? a.t : null, B_target: b ? b.t : null};
  }
  if (out.intent === 'SET_LOCATION' && a && (/[LA]/.test(a.flags) || a.t.indexOf('|') !== -1)) {
    // Not one spot: several spots, ashore, or a group ("I'm at the arcade": which one?).
    return {intent: 'LOCATION_REFUSED', A: out.A, A_target: a.t,
            reason: a.flags.indexOf('A') !== -1 ? 'ashore' : a.flags.indexOf('L') !== -1 ? 'multi_spot' : 'group'};
  }
  out.A_target = a ? a.t : null;
  if (a && (/[LA]/.test(a.flags) || a.t.indexOf('|') !== -1)) {
    // A start that isn't one spot (voicecard.js refuses it as a start, §9.6).
    out.A_spot = a.flags.indexOf('A') !== -1 ? 'ashore' : a.flags.indexOf('L') !== -1 ? 'multi_spot' : 'group';
  }
  out.B_target = b ? b.t : null;
  out.A_how = a ? a.how : null;
  out.B_how = b ? b.how : null;
  out.bare = p.bare;
  return out;
}

// ------------------------------------------------------------------ merge

var IN_SCOPE = {SET_LOCATION: 1, ROUTE: 1, ROUTE_COMBINED: 1, CLOSEST_RESTROOM: 1, CLOSEST_BAR: 1, CLOSEST_COFFEE: 1,
                LOCATION_REFUSED: 1};

// Several clauses -> one result (voice-commands.json slot_rules).
function merge(items, match) {
  var res = [];
  items.forEach(function(it) {
    if (!it.r) {
      return;
    }
    // A correction that is only a place replaces the previous result's last slot.
    var prev = res[res.length - 1];
    var bare = it.correction && it.p.intent === 'ROUTE' && it.p.bare ? it.p.B : null;
    if (bare && prev && IN_SCOPE[prev.p.intent]) {
      var p2 = copy(prev.p);
      p2[prev.p.intent === 'ROUTE' || prev.p.intent === 'ROUTE_COMBINED' ? 'B' : 'A'] = bare;
      res[res.length - 1] = {p: p2, r: resolve(p2, match)};
      return;
    }
    res.push(it);
  });
  // A bare place followed by a route without A: that place is A.
  for (var i = 0; i + 1 < res.length; i++) {
    var a = res[i].r, b = res[i + 1].r;
    if (a.intent === 'ROUTE' && a.bare && !a.A && b.intent === 'ROUTE' && !b.A) {
      var p3 = copy(res[i + 1].p);
      p3.A = a.B;
      res.splice(i, 2, {p: p3, r: resolve(p3, match)});
      i--;
    }
  }
  var rs = res.map(function(x) { return x.r; });
  var loc = null, act = null, refusal = null, last = null;
  rs.forEach(function(r) {
    if (IN_SCOPE[r.intent]) {
      last = r;
      if (r.intent === 'SET_LOCATION') {
        loc = r;
      } else if (r.intent === 'LOCATION_REFUSED') {
        refusal = r;
      } else {
        act = r;
      }
    }
  });
  if (act && loc && !act.A && (act.intent === 'ROUTE' || act.intent === 'CLOSEST_RESTROOM' ||
                             act.intent === 'CLOSEST_BAR' || act.intent === 'CLOSEST_COFFEE')) {
    var c = copy(act);
    c.A = loc.A;
    c.A_target = loc.A_target;
    c.A_how = loc.A_how;
    c.cabin = act.cabin || loc.cabin;
    c.A_spot = loc.A_spot;
    c.atA = true;  // A came from "I'm at": it also sets the spoken start (D4)
    if (act.intent === 'ROUTE') {
      c.intent = 'ROUTE_COMBINED';
    }
    return c;
  }
  if (refusal && act && !act.A) {
    return refusal;
  }
  if (last) {
    return last;
  }
  var order = ['OUT_OF_SCOPE_KNOWN', 'INCOMPLETE'];
  for (var k = 0; k < order.length; k++) {
    var of = rs.filter(function(r) { return r.intent === order[k]; });
    if (of.length) {
      return of[of.length - 1];
    }
  }
  return rs.length ? rs[rs.length - 1] : {intent: 'NO_MATCH', reason: 'empty'};
}

function parse(text, opts) {
  opts = opts || {};
  var isCabin = opts.isCabin || function() { return false; };
  var match = matcher(opts.ship);
  var items = normalise(text, isCabin).map(function(c) {
    var p = parseClause(c.text);
    return {p: p, r: resolve(p, match), correction: c.correction};
  });
  var r = merge(items, match);
  var out = {intent: r.intent, A: r.A || null, B: r.B || null, cabin: r.cabin || null,
             A_target: r.A_target || null, B_target: r.B_target || null, A_how: r.A_how || null, B_how: r.B_how || null};
  if (r.intent === 'ROUTE_COMBINED') {
    r.atA = true;
  }
  ['reason', 'topic', 'deck', 'via', 'A_spot', 'atA'].forEach(function(k) {
    if (r[k]) {
      out[k] = r[k];
    }
  });
  if (out.intent === 'OUT_OF_SCOPE_KNOWN' || out.intent === 'INCOMPLETE' || (out.intent === 'NO_MATCH' && out.reason !== 'not_mapped')) {
    out.A_target = out.B_target = out.A_how = out.B_how = null;
  }
  return out;
}

// The places a category request chooses from (flags in the generated lexicon:
// B bars, C coffee); the route planner picks the nearest, like the nearest restroom.
function flagged(ship, flag) {
  var d = DATA[ship || 'HM'];
  if (!d) {
    return [];
  }
  return d.t.filter(function(t, i) { return (d.f[i] || '').indexOf(flag) !== -1; });
}

function bars(ship) {
  return flagged(ship, 'B');
}

function coffee(ship) {
  return flagged(ship, 'C');
}

