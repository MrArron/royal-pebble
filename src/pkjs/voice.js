// ------------------------------------------------------------------ helpers

function trim(s) {
  return String(s).replace(/\s+/g, ' ').replace(/^ | $/g, '');
}

function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Whole-word regex over phrases (longest first) or over a regex source.
function wordsRx(list, flags) {
  var l = list.slice().sort(function(a, b) { return b.length - a.length; });
  return srcRx(l.map(esc).join('|'), flags);
}

function srcRx(src, flags) {
  return new RegExp('(^| )(?:' + src + ')(?= |$)', flags === undefined ? 'g' : flags);
}

function startRx(list, end) {
  return list.map(function(s) { return new RegExp('^(?:' + s + ')' + (end || '(?= |$)')); });
}

function anyTest(list, s) {
  for (var i = 0; i < list.length; i++) {
    if (list[i].test(s)) {
      return true;
    }
  }
  return false;
}

function copy(o) {
  var c = {};
  Object.keys(o).forEach(function(k) { c[k] = o[k]; });
  return c;
}

