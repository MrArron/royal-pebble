var UNITS = {zero: 0, oh: 0, o: 0, one: 1, two: 2, three: 3, four: 4, five: 5, six: 6, seven: 7, eight: 8, nine: 9};
var TEENS = {ten: 10, eleven: 11, twelve: 12, thirteen: 13, fourteen: 14, fifteen: 15, sixteen: 16, seventeen: 17,
  eighteen: 18, nineteen: 19};
var TENS = {twenty: 20, thirty: 30, forty: 40, fifty: 50, sixty: 60, seventy: 70, eighty: 80, ninety: 90};
var CONNECT = {to: '2', too: '2', 'for': '4'};  // may be a digit inside a run of numbers
var NO_TO_BEFORE = {deck: 1, room: 1, level: 1, floor: 1, cabin: 1, stateroom: 1, number: 1, suite: 1};

function isNumWord(w) {
  return /^\d+$/.test(w) || (w in TEENS) || (w in TENS) || w === 'hundred' || w === 'thousand' ||
    ((w in UNITS) && w !== 'oh' && w !== 'o');
}

// The words of one run of numbers -> digit groups, some marked as a possible
// "to"/"for": [{d: '89'}, {sep: 'to', d: '2'}, ...]. Spoken groups are joined
// later ("eighty-nine twenty-four" -> 89, 24 -> 8924).
function runGroups(words) {
  var out = [];
  var cur = null, scale = false, tensOpen = false;
  function flush() {
    if (cur !== null) {
      out.push({d: String(cur)});
    }
    cur = null; scale = false; tensOpen = false;
  }
  words.forEach(function(w) {
    if (/^\d+$/.test(w)) {
      flush(); out.push({d: w});
    } else if (w in CONNECT) {
      flush(); out.push({sep: w === 'for' ? 'for' : 'to', d: CONNECT[w]});
    } else if (w in UNITS) {
      var v = UNITS[w];
      if (cur !== null && (tensOpen || scale) && v > 0) {
        cur += v; tensOpen = false; scale = false;
      } else {
        flush(); cur = v;
      }
    } else if (w in TEENS) {
      if (cur !== null && scale) {
        cur += TEENS[w]; scale = false;
      } else {
        flush(); cur = TEENS[w];
      }
    } else if (w in TENS) {
      if (cur !== null && scale) {
        cur += TENS[w];
      } else {
        flush(); cur = TENS[w];
      }
      tensOpen = true; scale = false;
    } else if (w === 'hundred') {
      cur = cur === null ? 100 : Math.floor(cur / 1000) * 1000 + (cur % 1000) * 100;
      scale = true; tensOpen = false;
    } else if (w === 'thousand') {
      cur = (cur === null ? 1 : cur) * 1000; scale = true; tensOpen = false;
    }
  });
  flush();
  return out;
}

// Real cabins count most, then 4-5 digit numbers; each "to" costs a little.
function chunkScore(chunks, isCabin, deckCtx) {
  var score = 0;
  chunks.forEach(function(c, j) {
    if (j === 0 && deckCtx && c.length <= 2) {
      score += 10;
    } else if (isCabin(c)) {
      score += 10;
    } else if (c.length === 4 || c.length === 5) {
      score += 1;
    }
  });
  return score - (chunks.length - 1) * 0.5;
}

// Picks digit-or-word for each possible separator: "8924 to 6902", "8924".
function chooseReading(groups, isCabin, deckCtx) {
  var opt = [];
  groups.forEach(function(g, i) {
    if (g.sep) {
      opt.push(i);
    }
  });
  var n = Math.min(opt.length, 6);
  var best = null;
  for (var mask = 0; mask < (1 << n); mask++) {
    var chunks = [''], seps = [], ok = true;
    for (var i = 0; i < groups.length && ok; i++) {
      var k = opt.indexOf(i);
      if (k !== -1 && k < n && (mask & (1 << k))) {
        ok = chunks[chunks.length - 1] !== '';
        seps.push(groups[i].sep);
        chunks.push('');
      } else {
        chunks[chunks.length - 1] += groups[i].d;
      }
    }
    if (ok && chunks[chunks.length - 1] !== '') {
      var score = chunkScore(chunks, isCabin, deckCtx);
      if (!best || score > best.score) {
        best = {score: score, chunks: chunks, seps: seps};
      }
    }
  }
  if (!best) {
    return {text: groups.map(function(g) { return g.d; }).join(''), score: 0};
  }
  var s = best.chunks[0];
  for (var j = 0; j < best.seps.length; j++) {
    s += ' ' + best.seps[j] + ' ' + best.chunks[j + 1];
  }
  return {text: s, score: best.score};
}

// Number words -> digits in one clause, deciding "to"/"two" by the cabin list.
function numbers(clause, isCabin) {
  var w = clause.split(' ');
  var out = [];
  var i = 0;
  function num(j) {
    if (j < 0 || j >= w.length) {
      return false;
    }
    return isNumWord(w[j]) || ((w[j] === 'oh' || w[j] === 'o') && (isNumWord(w[j - 1] || '') || isNumWord(w[j + 1] || '')));
  }
  while (i < w.length) {
    if (!num(i)) {
      out.push(w[i]);
      i++;
      continue;
    }
    var run = [];
    while (i < w.length && (num(i) || ((w[i] in CONNECT) && run.length && num(i + 1)))) {
      run.push(w[i]);
      i++;
    }
    var before = out.length ? out[out.length - 1] : '';
    var deckCtx = before === 'deck';
    var more = i < w.length;
    var groups = runGroups(run);
    var last = groups[groups.length - 1];
    if (more && last && !last.sep && last.d === '2' && groups.length > 1) {
      // A final "two" before more words may be "to": "8924 two the Solarium".
      var withTwo = chooseReading(groups, isCabin, deckCtx);
      var without = chooseReading(groups.slice(0, -1), isCabin, deckCtx);
      if (without.score - 0.5 > withTwo.score) {
        out.push(without.text, 'to');
      } else {
        out.push(withTwo.text);
      }
    } else if (more && groups.length === 1 && /^\d{5,6}$/.test(last.d) && /2$/.test(last.d) &&
               !isCabin(last.d) && isCabin(last.d.slice(0, -1))) {
      out.push(last.d.slice(0, -1), 'to');  // "89242 the Solarium": a "to" glued on
    } else if (groups.length === 1 && last.d === '2' && run.length === 1 &&
               out.length && more && !(before in NO_TO_BEFORE)) {
      out.push('to');  // a lone "two" between words
    } else if (last.sep) {
      out.push(chooseReading(groups.slice(0, -1), isCabin, deckCtx).text, 'to');
    } else {
      out.push(chooseReading(groups, isCabin, deckCtx).text);
    }
  }
  return out.join(' ');
}

// ------------------------------------------------------------------ normalise

// The shared first steps for transcripts and lexicon phrases: lowercase, no
// accents, & -> and, digit punctuation, no apostrophes, "(Ages 6-12)" dropped.
function clean(raw) {
  return String(raw || '').replace(/[\u2018\u2019\u02bc`]/g, "'").replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u00e9\u00e8]/g, 'e').toLowerCase()
    .replace(/\(ages[^)]*\)/g, ' ')
    .replace(/(\d),(?=\d{3}(?:\D|$))/g, '$1').replace(/(\d)-(?=\d)/g, '$1 ').replace(/#\s*(?=\d)/g, '')
    .replace(/&/g, ' and ').replace(/([a-z])-(?=[a-z])/g, '$1 ');
}

function words(s) {
  return trim(s.replace(/'/g, '').replace(/[^a-z0-9@ ]+/g, ' '));
}

function stripFillers(s) {
  var prev;
  do {
    prev = s;
    s = trim(s.replace(RX.filler, '$1'));
  } while (s !== prev);
  return s;
}

// Category words -> tokens (order matters, see GRAMMAR).
function categories(s, isCabin) {
  var cw = G.cabinWords;
  s = ' ' + s + ' ';
  s = s.replace(RX.restroom, '$1@restroom');
  s = s.replace(RX.fore, '$1@forelev').replace(RX.aft, '$1@aftelev').replace(RX.elevator, '$1@elevator');
  s = s.replace(RX.stairs, '$1@stairs');
  s = s.replace(new RegExp(' deck (\\d{1,2}) ' + cw + ' (?:number )?(\\d{3})(?= )', 'g'), function(m, d, n) {
    return isCabin(d + n) ? ' @cabin:' + d + n : m;
  });
  s = s.replace(new RegExp(' ' + cw + ' (?:number )?(\\d{3}) on deck (\\d{1,2})(?= )', 'g'), function(m, n, d) {
    return isCabin(d + n) ? ' @cabin:' + d + n : m;
  });
  s = s.replace(new RegExp(' (?:' + cw + ') (?:number |no |is )?(\\d{3,5})(?= )', 'g'), ' @cabin:$1');
  s = s.replace(/ (\d{4,5})(?= )/g, function(m, n) { return isCabin(n) ? ' @cabin:' + n : m; });
  s = s.replace(/ deck (\d{1,2})(?= )/g, ' @deck:$1');
  s = s.replace(RX.myCabin, '$1@mycabin');
  s = s.replace(/ (to|near|from|by|for) me(?= $)/g, ' $1 @here');
  s = s.replace(RX.here, '$1@here');
  s = s.replace(/ (?:too|tu)(?= )/g, ' to');
  return trim(s);
}

// Cut before a strong trigger in mid-sentence ("... escape room how do I get").
function splitClauses(s) {
  var parts = [], last = 0, m;
  RX.starter.lastIndex = 0;
  while ((m = RX.starter.exec(s)) !== null) {
    var at = m.index;
    if (RX.starter.lastIndex === at) {
      RX.starter.lastIndex++;
    }
    if (at === 0) {
      continue;
    }
    var prev = s.slice(0, at).split(' ').pop();
    var next = s.slice(at + m[0].length).split(' ')[0];
    if (prev === 'iam' || prev === 'i' || prev === 'we' ||
        ((prev === 'the' || prev === 'is') && (next === 'closest' || next === 'nearest'))) {
      continue;
    }
    parts.push(s.slice(last, at));
    last = at + m[0].length;
  }
  parts.push(s.slice(last));
  return parts.map(trim).filter(function(p) { return p; });
}

// Transcript -> clauses [{text, correction}].
function normalise(raw, isCabin) {
  var clauses = [];
  clean(raw).split(/[.?!;:\u2026]+(?=\s|$)/).forEach(function(sen) {
    sen = words(sen);
    if (!sen) {
      return;
    }
    RX.contractions.forEach(function(p) { sen = trim(sen.replace(p[0], p[1])); });
    sen = numbers(sen, isCabin);
    // A correction word at the start flags the sentence; one inside splits it.
    var pieces = [], corr = false, m;
    if ((m = sen.match(RX.correctionStart))) {
      corr = true;
      sen = trim(sen.slice(m[0].length));
    }
    while ((m = RX.correction.exec(sen)) !== null && m.index > 0) {
      var after = trim(sen.slice(m.index + m[0].length));
      if (!after) {
        break;
      }
      pieces.push({text: sen.slice(0, m.index), correction: corr});
      corr = true;
      sen = after;
    }
    pieces.push({text: sen, correction: corr});
    pieces.forEach(function(p) {
      splitClauses(categories(stripFillers(p.text), isCabin)).forEach(function(c, k) {
        clauses.push({text: c, correction: p.correction && k === 0});
      });
    });
  });
  return clauses;
}

