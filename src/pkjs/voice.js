// A phrase with spaces, "the" and punctuation gone: "The Wind Jammer" ->
// "windjammer". The generator squashes the lexicon with this same function.
function squash(s) {
  var w = numbers(words(clean(s)), function() { return false; });
  return (' ' + w + ' ').replace(/ the(?= )/g, ' ').replace(/theatre/g, 'theater').replace(/centre/g, 'center')
    .replace(/[^a-z0-9|]/g, '');
}

// Optimal string alignment distance (edits, with swaps), stopping past max.
function distance(a, b, max) {
  if (Math.abs(a.length - b.length) > max) {
    return max + 1;
  }
  var d = [], i, j;
  for (i = 0; i <= a.length; i++) {
    d[i] = [i];
  }
  for (j = 0; j <= b.length; j++) {
    d[0][j] = j;
  }
  for (i = 1; i <= a.length; i++) {
    var low = max + 1;
    for (j = 1; j <= b.length; j++) {
      var c = a[i - 1] === b[j - 1] ? 0 : 1;
      var v = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + c);
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) {
        v = Math.min(v, d[i - 2][j - 2] + 1);
      }
      d[i][j] = v;
      low = Math.min(low, v);
    }
    if (low > max) {
      return max + 1;
    }
  }
  return d[a.length][b.length];
}

var matchers = {};

// match(span, deck) -> {t: target name, i: index, flags, how: 'exact' | 'part' |
// 'fuzzy'} or null. Matching order:
//  1. the whole span, with the deck said ("main dining room" + 5), then as is,
//     then without a final s;
//  2. the longest run of words that is a phrase, when the rest is only noise
//     words or 3 letters ("the wind jam are", "the Cartier store");
//  3. fuzzy, 5+ letters, only when one target is clearly closest: most of one
//     target's phrase (70%+), 1 edit (5-7 letters) or 2 (8+), or a 7+ letter
//     phrase followed by up to 3 letters of noise.
function makeMatcher(lex) {
  var map = {};
  var keys = [];
  function put(k, i) {
    if (k && !Object.prototype.hasOwnProperty.call(map, k)) {
      map[k] = i;
      keys.push(k);
    }
  }
  // Stored phrases first: a group's phrase ("arcade") beats a member's name.
  lex.t.forEach(function(name, i) {
    (lex.p[i] ? lex.p[i].split('|') : []).forEach(function(k) { put(k, i); });
  });
  lex.t.forEach(function(name, i) {
    if (name.indexOf('|') === -1) {
      put(squash(name), i);
    }
  });
  function hit(i, how) {
    return {t: lex.t[i], i: i, flags: lex.f[i] || '', how: how};
  }
  function exact(c) {
    if (Object.prototype.hasOwnProperty.call(map, c)) {
      return map[c];
    }
    if (c.length >= 6 && c.charAt(c.length - 1) === 's' && Object.prototype.hasOwnProperty.call(map, c.slice(0, -1))) {
      return map[c.slice(0, -1)];
    }
    return -1;
  }
  function unique(list) {
    var t = -1;
    for (var i = 0; i < list.length; i++) {
      if (t !== -1 && map[list[i]] !== t) {
        return -1;
      }
      t = map[list[i]];
    }
    return t;
  }
  function fuzzy(c) {
    if (c.length < 5) {
      return -1;
    }
    // A clipped name: most of a phrase ("splashawayb"), from one target only
    // ("solar" could be Solarium, Solarium Bar or Solarium Bistro: none).
    var starts = keys.filter(function(k) { return k.indexOf(c) === 0; });
    if (starts.length) {
      var most = starts.every(function(k) { return c.length >= 0.7 * k.length; });
      return most ? unique(starts) : -1;
    }
    var max = c.length >= 8 ? 2 : 1;
    var best = -1, bestD = max + 1, second = max + 2;
    keys.forEach(function(k) {
      var d = distance(c, k, max + 1);
      if (d < bestD) {
        if (best !== -1 && map[k] !== best) {
          second = bestD;
        }
        best = map[k];
        bestD = d;
      } else if (map[k] !== best && d < second) {
        second = d;
      }
    });
    if (best !== -1 && bestD <= max && second > bestD) {
      return best;
    }
    return unique(keys.filter(function(k) { return k.length >= 7 && c.indexOf(k) === 0 && c.length - k.length <= 3; }));
  }
  return function(span, deck) {
    var c = squash(span || '');
    if (!c) {
      return null;
    }
    var i = deck ? exact(c + deck) : -1;
    if (i === -1) {
      i = exact(c);
    }
    if (i !== -1) {
      return hit(i, 'exact');
    }
    var w = words(clean(span)).split(' ');
    for (var len = w.length - 1; len >= 1; len--) {
      for (var s = 0; s + len <= w.length; s++) {
        var rest = w.slice(0, s).concat(w.slice(s + len));
        var left = rest.join('');
        var noise = rest.every(function(x) { return NOISE[x] || x === 'the'; }) || (left.length <= 3 && !/\d/.test(left));
        var k = noise ? exact(squash(w.slice(s, s + len).join(' '))) : -1;
        if (k !== -1) {
          return hit(k, 'part');
        }
      }
    }
    i = fuzzy(c);
    return i === -1 ? null : hit(i, 'fuzzy');
  };
}

function matcher(ship) {
  ship = ship || 'HM';
  if (!matchers[ship]) {
    matchers[ship] = DATA[ship] ? makeMatcher(DATA[ship]) : function() { return null; };
  }
  return matchers[ship];
}

// ------------------------------------------------------------------ clauses

function cleanSpan(s) {
  s = trim(s || '');
  var changed = true;
  while (changed) {
    changed = false;
    LEAD.forEach(function(l) {
      if (s.indexOf(l + ' ') === 0) {
        s = s.slice(l.length + 1);
        changed = true;
      }
    });
    TAIL.forEach(function(t) {
      t = ' ' + t;
      if (s.length > t.length && s.slice(-t.length) === t) {
        s = s.slice(0, -t.length);
        changed = true;
      }
    });
    if (s === '@here') {
      return s;
    }
  }
  return trim(s);
}

// "main dining room on @deck:5" -> {span: 'main dining room', deck: 5}.
function deckHint(span) {
  var m = span.match(/^(.+?) (?:on|at) @deck:(\d{1,2})$/);
  if (m) {
    return {span: m[1], deck: +m[2]};
  }
  m = span.match(/^@deck:(\d{1,2}) (?:near|by|at|next to|on|in) (.+)$/);
  return m ? {span: m[2], deck: +m[1]} : {span: span, deck: null};
}

// Category requests (owner, 2026-09-28; voice only): a span that asks for any
// bar, any coffee, or a bite to eat, not a named venue.
// - CLOSEST_BAR: the nearest bar flagged B, found like the nearest restroom.
//   "Schooner Bar", "Sand Bar" and "the pub" (Boot & Bonnet Pub) stay venues;
//   "wine bar" has two candidates and is left to the venue matcher.
// - CLOSEST_COFFEE: the nearest place flagged C (Starbucks, Cafe Promenade,
//   Park Cafe). "Starbucks" said by name stays a venue.
// - SNACK: Cafe Promenade, open 24 hours (owner), for a snack or a bite
//   outside dining hours. "Pizza" stays Sorrento's.
var PLACE_FOR = '(?:(?:place|spot|somewhere|where)(?: (?:i|we) can)?(?: to| for)?' +
  '(?: (?:get|grab|have|buy|order|find))?(?: (?:a|an|some|me a|me some))? )?';
var CATEGORY_SPANS = [
  {intent: 'CLOSEST_BAR', what: 'bar', rx: new RegExp('^(?:(?:the|a|an|any|some) )?(?:(?:closest|nearest|close|near|nearby|next|good) )?' +
    PLACE_FOR + '(?:bars?|drinks?|cocktails?|beers?|(?:a )?glass of wine|booze|alcohol|(?:a )?margarita|(?:a )?mojito)' +
    '(?: (?:near @here|near me|nearby|around here|close by))?$')},
  {intent: 'CLOSEST_COFFEE', what: 'coffee', rx: new RegExp('^(?:(?:the|a|an|any|some) )?(?:(?:closest|nearest|close|near|nearby|next|good) )?' +
    PLACE_FOR + '(?:(?:cup of )?coffee|coffee shop|coffee place|cafe|latte|espresso|cappuccino|iced coffee|caffeine)' +
    '(?: (?:near @here|near me|nearby|around here|close by))?$')},
  {intent: 'SNACK', what: 'snack', rx: new RegExp('^(?:(?:the|a|an|any|some) )?(?:(?:closest|nearest|close|near|nearby|next|late night|24 hour|twenty four hour) )?' +
    PLACE_FOR + '(?:snacks?|(?:quick |late night )?(?:bite|food|eats?)(?: to eat)?|something (?:to eat|small)|eat|(?:a )?sandwich|(?:a )?cookie|midnight snack|(?:i am|iam|im) hungry|hungry|starving)' +
    '(?: (?:near @here|near me|nearby|around here|close by|now|right now|at night|late))?$')}
];
var SNACK_PLACE = 'Cafe Promenade';

// Which category a span asks for (CATEGORY_SPANS entry), or null.
function categoryOf(v) {
  if (!v) {
    return null;
  }
  for (var i = 0; i < CATEGORY_SPANS.length; i++) {
    if (CATEGORY_SPANS[i].rx.test(v)) {
      return CATEGORY_SPANS[i];
    }
  }
  return null;
}

// A whole request the route patterns don't catch ("where can we get drinks",
// "I could use a coffee", "I'm hungry").
var CATEGORY_LEAD = /^(?:(?:where|how) (?:can|could|do|would) (?:i|we) |(?:i|we) (?:need|want|would like|could use|could go for) |(?:lets|let us) )?(?:(?:go )?(?:get|grab|find|buy|order|have) )?/;

function categoryRequest(v) {
  return v ? categoryOf(v) || categoryOf(v.replace(CATEGORY_LEAD, '')) : null;
}

function refusedReason(v) {
  var cat = categoryOf(v);
  if (cat && cat.intent !== 'SNACK') {
    return cat.what;  // many bars, many coffee places
  }
  if (/^@restroom/.test(v || '')) {
    return 'restroom';
  }
  if (/^@(?:elevator|forelev|aftelev)/.test(v || '')) {
    return 'elevator';
  }
  if (/^@stairs/.test(v || '')) {
    return 'stairs';
  }
  return /^@deck:/.test(v || '') ? 'deck' : null;
}

function refused(v) {
  return {intent: 'LOCATION_REFUSED', A: v, reason: refusedReason(v)};
}

function locationSpan(rest) {
  var s = rest, moved = true;
  while (moved) {
    moved = false;
    G.locationAdverbs.forEach(function(a) {
      if (s.indexOf(a + ' ') === 0) {
        s = s.slice(a.length + 1);
        moved = true;
      }
    });
  }
  if (s === '@mycabin') {
    return s;
  }
  for (var j = 0; j < G.locationPreps.length; j++) {
    var p = G.locationPreps[j];
    if (s === p) {
      return '';
    }
    if (s.indexOf(p + ' ') === 0) {
      return s.slice(p.length + 1);
    }
  }
  return null;
}

function setLocation(span) {
  var to = trim(span).match(/^(.+?) to (.+)$/);
  if (to) {
    return {intent: 'ROUTE_COMBINED', A: cleanSpan(to[1]), B: cleanSpan(to[2])};
  }
  var d = deckHint(cleanSpan(span));
  if (!d.span || d.span === '@here') {
    return {intent: 'INCOMPLETE'};
  }
  return {intent: 'SET_LOCATION', A: d.span, deck: d.deck};
}

function stripTrigger(c) {
  for (var i = 0; i < RX.route.length; i++) {
    var m = c.match(RX.route[i]);
    if (m) {
      return {rest: trim(c.slice(m[0].length)), where: anyTest(RX.where, c)};
    }
  }
  return null;
}

// Splits what follows a trigger into A and B, first pattern wins.
function routeRest(rest) {
  var m;
  rest = rest.replace(/^(?:over to|up to|down to|back to|the way to|the way) /, 'to ');
  if ((m = rest.match(/^from (.+?) (?:to|towards|toward) (.+)$/)) || (m = rest.match(/^(?:for|front|form|fro) (.+?) to (.+)$/))) {
    return {A: m[1], B: m[2]};
  }
  if ((m = rest.match(/^(?:(?:to|towards|toward|into|for) )?(.+?) (?:from|starting from|starting at|coming from|leaving from|leaving) (.+)$/))) {
    return {A: m[2], B: m[1]};
  }
  if ((m = rest.match(/^from (.+)$/))) {
    return {A: m[1], B: ''};
  }
  if ((m = rest.match(/^(?:to|towards|toward|into|for) (.+)$/))) {
    return {A: null, B: m[1]};
  }
  if ((m = rest.match(/^(.+?) to (.+)$/))) {
    return {A: m[1], B: m[2]};
  }
  return {A: null, B: /^(?:to|towards|toward|into|for)$/.test(rest) ? '' : rest};
}

function restroomClause(c) {
  if (/(?:^| )(?:from|leaving|starting at) (?:the |a )?@restroom(?: |$)/.test(c)) {
    return refused('@restroom');
  }
  var loc = c.match(/^iam (.*)$/);
  var sp = loc ? locationSpan(loc[1]) : null;
  if (sp !== null && /@restroom/.test(sp)) {
    return refused('@restroom');
  }
  var t = stripTrigger(c);
  var s = t ? t.rest : c;
  var m, A = null;
  if ((m = s.match(/@restroom (?:from|near|by|to|next to|close to|closest to|nearest to|around|at|in|on|for|off|nearby) (.+)$/)) ||
      (m = s.match(/(?:^| )(?:from|at|near|by) (.+?) (?:to|towards) (?:the |a )?(?:closest |nearest )?@restroom/)) ||
      (m = s.match(/^(.+?) (?:to|towards) (?:the |a )?(?:closest |nearest )?@restroom/))) {
    A = cleanSpan(m[1]);
  }
  if (A === '@here') {
    A = null;
  }
  var d = A ? deckHint(A) : {span: null, deck: null};
  var dm = /^@deck:(\d{1,2})$/.exec(d.span || '');
  if (dm) {
    return {intent: 'CLOSEST_RESTROOM', A: null, deck: +dm[1]};  // "closest restroom on deck 5": a hint
  }
  if (refusedReason(d.span)) {
    return refused(d.span);
  }
  return {intent: 'CLOSEST_RESTROOM', A: d.span, deck: d.deck};
}

// One clause -> intent with slot spans (not matched yet).
function parseClause(c) {
  var m, i;
  if (anyTest(RX.stateroom, c)) {
    return {intent: 'OUT_OF_SCOPE_KNOWN', topic: 'stateroom'};
  }
  if (anyTest(RX.hours, c)) {
    return {intent: 'OUT_OF_SCOPE_KNOWN', topic: 'hours'};
  }
  if (anyTest(RX.schedule, c)) {
    return {intent: 'OUT_OF_SCOPE_KNOWN', topic: 'schedule'};
  }
  if (/@restroom/.test(c)) {
    return restroomClause(c);
  }
  if ((m = c.match(/^iam (.*)$/))) {
    var span = locationSpan(m[1]);
    if (span !== null) {
      return span === '' ? {intent: 'INCOMPLETE'} : setLocation(span);
    }
  }
  if ((m = c.match(/^(?:currently |now )?(at|near|outside|next to|in) (.+)$/)) && !/ to /.test(m[2])) {
    return setLocation(m[2]);
  }
  for (i = 0; i < RX.locOther.length; i++) {
    if ((m = c.match(RX.locOther[i]))) {
      return setLocation(m[1] || m[2] || '');
    }
  }
  var t = stripTrigger(c);
  var r;
  if (t) {
    if (!t.rest) {
      return anyTest(RX.back, c) ? {intent: 'ROUTE', A: null, B: '@mycabin', trigger: true} : {intent: 'INCOMPLETE'};
    }
    r = routeRest(t.rest);
    if (t.where) {
      r.B = (r.B || '').replace(/ (?:on|located|at)$/, '');
    }
  } else {
    r = routeRest(c);
  }
  var A = r.A === null ? null : cleanSpan(r.A);
  var B = cleanSpan(r.B);
  if (A === '@here') {
    A = null;
  }
  if (!B || B === 'there' || B === '@here') {
    return {intent: 'INCOMPLETE'};
  }
  if (B === 'back' || B === 'back home') {
    B = '@mycabin';
  }
  var dA = A ? deckHint(A) : {span: null, deck: null};
  var dB = deckHint(B);
  if (refusedReason(dA.span)) {
    return refused(dA.span);
  }
  return {intent: 'ROUTE', A: dA.span, B: dB.span, deckA: dA.deck, deck: dB.deck, trigger: !!t, bare: !t && r.A === null};
}

